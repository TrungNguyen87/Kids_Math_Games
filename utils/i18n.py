def init_language():
    if "language" not in st.session_state:
        st.session_state.language = DEFAULT_LANGUAGE


def t(key: str, **kwargs) -> str:
    """Translate a key into the currently selected language."""
    lang = st.session_state.get("language", DEFAULT_LANGUAGE)
    text = TRANSLATIONS.get(lang, {}).get(key)
    if text is None:
        # Fall back to Dutch, then to the raw key so missing translations
        # never crash the app.
        text = TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text


def language_switcher(location=st.sidebar):
    """Render the NL / EN toggle. Call once per page (usually in the sidebar)."""
    init_language()
    codes = list(LANGUAGES.keys())
    labels = [LANGUAGES[c] for c in codes]
    current_index = codes.index(st.session_state.language)

    def _on_change():
        st.session_state.language = st.session_state["_lang_choice_raw"]

    location.radio(
        t("sidebar.language"),
        options=codes,
        format_func=lambda c: LANGUAGES[c],
        index=current_index,
        key="_lang_choice_raw",
        horizontal=True,
        on_change=_on_change,
    )
